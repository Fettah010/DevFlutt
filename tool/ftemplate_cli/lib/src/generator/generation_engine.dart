import 'dart:io';

import 'package:mason/mason.dart';
import 'package:path/path.dart' as p;

import '../models/generation_plan.dart';
import '../metadata/template_metadata.dart';
import 'generated_dart_formatter.dart';

/// The outcome of a generation run.
class GenerationResult {
  const GenerationResult({required this.projectDir, required this.files, required this.metadata});

  /// The directory holding the generated project (a temp directory).
  final Directory projectDir;

  /// The files Mason reported as generated.
  final List<GeneratedFile> files;

  /// The parsed template metadata.
  final Map<String, dynamic> metadata;
}

/// Generates a project into a temporary directory using Mason.
class GenerationEngine {
  GenerationEngine({required this.brickPath, this.metadata = const TemplateMetadata()});

  /// Path to the Mason brick that produces the project scaffold.
  final String brickPath;

  /// The metadata writer.
  final TemplateMetadata metadata;

  /// Generates the project for [plan] into a fresh temporary directory.
  ///
  /// The caller is responsible for moving [GenerationResult.projectDir] into
  /// place and for cleaning it up on failure.
  Future<GenerationResult> generate(GenerationPlan plan) async {
    final tempDir = await Directory.systemTemp.createTemp('ftemplate_');
    try {
      final generator = await MasonGenerator.fromBrick(Brick.path(brickPath));
      final target = DirectoryGeneratorTarget(tempDir);
      final files = await generator.generate(target, vars: _vars(plan));

      GeneratedDartFormatter().format(tempDir);

      await metadata.write(tempDir, plan);
      final loaded = readMetadata(tempDir) ?? <String, dynamic>{};

      return GenerationResult(projectDir: tempDir, files: files, metadata: loaded);
    } catch (_) {
      await tempDir.delete(recursive: true);
      rethrow;
    }
  }

  Map<String, dynamic> _vars(GenerationPlan plan) {
    final moduleIds = plan.modules.map((module) => module.id).toSet();
    return {
      'projectName': plan.spec.projectName,
      'projectDescription': '${plan.spec.name} — generated by the DevFlutt template.',
      'org': plan.spec.org,
      'applicationId': plan.spec.applicationId,
      'packagePath': plan.spec.applicationId.replaceAll('.', '/'),
      'hasArchitectureCore': moduleIds.contains('architecture-core'),
      'hasStateRiverpod': moduleIds.contains('state-riverpod'),
      'hasGoRouter': moduleIds.contains('navigation'),
      'hasDesignSystem': moduleIds.contains('design-system'),
      'hasFeatureExample': moduleIds.contains('feature-example'),
      'hasShowcase': moduleIds.contains('showcase'),
      'hasLogging': moduleIds.contains('logging'),
      'hasNetworking': moduleIds.contains('networking'),
      'hasSecureStorage': moduleIds.contains('secure-storage'),
      'hasDiagnostics': moduleIds.contains('diagnostics'),
      'hasAuthCore': moduleIds.contains('auth-core'),
      'hasAuthRest': moduleIds.contains('auth-rest'),
      'hasAuthFirebase': moduleIds.contains('auth-firebase'),
      'hasAuthSupabase': moduleIds.contains('auth-supabase'),
      'hasAuth': _authAdapterModuleIds.any(moduleIds.contains),
      'hasAuthRouter':
          _authAdapterModuleIds.any(moduleIds.contains) && moduleIds.contains('navigation'),
      'hasServices': _serviceModuleIds.any(moduleIds.contains),
      'extraDependencies': plan.dependencies
          .map((dependency) => '${dependency.name}: ${dependency.version}')
          .toList(),
    };
  }

  /// The modules that contribute a service to the generated composition root.
  static const List<String> _serviceModuleIds = <String>[
    'logging',
    'networking',
    'secure-storage',
    'diagnostics',
  ];

  /// The modules that contribute an authentication adapter.
  ///
  /// At most one of them can be selected; the compatibility graph rejects a
  /// selection of two.
  static const List<String> _authAdapterModuleIds = <String>[
    'auth-rest',
    'auth-firebase',
    'auth-supabase',
  ];

  /// Whether [directory] exists and is non-empty.
  static bool isNonEmpty(Directory directory) {
    if (!directory.existsSync()) {
      return false;
    }
    return directory.listSync().isNotEmpty;
  }

  /// Moves the contents of [source] into [destination].
  static Future<void> moveInto(Directory source, Directory destination) async {
    await destination.create(recursive: true);
    await for (final entity in source.list()) {
      final targetPath = p.join(destination.path, p.basename(entity.path));
      await entity.rename(targetPath);
    }
    await source.delete();
  }
}
