// Assertions for the screen that the blank template actually ships.
import 'package:flutter_test/flutter_test.dart';
import 'package:patrol/patrol.dart';

class HomePage {
  HomePage(this.$);

  final PatrolIntegrationTester $;

  static const title = 'Home';
  static const description = 'Your app is ready';
  static const subtitle = 'Generated by the DevFlutt template.';
  static const logoSemantics = 'Flutter logo';

  Future<void> waitUntilVisible() async {
    await $(title).waitUntilVisible(timeout: const Duration(seconds: 10));
    await $(description).waitUntilVisible(timeout: const Duration(seconds: 10));
  }

  void expectContent() {
    expect($(title), findsOneWidget);
    expect($(description), findsOneWidget);
    expect($(subtitle), findsOneWidget);
    final semantics = $.tester.ensureSemantics();
    try {
      expect(find.bySemanticsLabel(logoSemantics), findsOneWidget);
    } finally {
      semantics.dispose();
    }
  }
}
