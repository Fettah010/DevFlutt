/// Page object for the DevFlutt home screen.
///
/// The HomePage widget does not use explicit `Key` values, so this page
/// object relies on text-based finders defined in
/// `lib/features/home/home_page.dart`.
library devflutt_patrol_pages.home_page;

import 'package:flutter_test/flutter_test.dart';
import 'package:patrol/patrol.dart';

import 'base_page.dart';

class HomePage extends BasePage {
  HomePage(super.$);

  // Text finders (matching home_page.dart)
  static const String titleText = 'Home';
  static const String descriptionText = 'Your app is ready';
  static const String subtitleText = 'Generated by the DevFlutt template.';

  @override
  Future<void> waitForPage() async {
    await $(titleText).waitUntilVisible();
    await $(descriptionText).waitUntilVisible();
  }

  @override
  Future<void> verifyContent() async {
    expect($(titleText), findsOneWidget);
    expect($(descriptionText), findsOneWidget);
    expect($(subtitleText), findsOneWidget);
  }

  /// Verifies that the page renders without overflow at the given text scale.
  Future<void> verifyNoOverflow(double textScale) async {
    // Patrol runs on real devices/emulators, so text scaling is handled by
    // the OS. This is a placeholder for future text-scale verification.
    // Widget-level text scale tests remain in test/widget/app_theme_test.dart.
  }
}